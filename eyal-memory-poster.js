(function(){
'use strict';
const card=document.getElementById('eyal');
if(!card||document.getElementById('eyalMemoryPoster'))return;
const path='assets/memories/eyal-plonter-elegant.png';
const section=document.createElement('section');
section.id='eyalMemoryPoster';
section.className='eyal-memory-poster';
section.setAttribute('aria-label','הזיכרון של אייל: הפטנט של סבתא שולי');
const heading=document.createElement('h4');
heading.textContent='הזיכרון של אייל וסבתא שולי';
const intro=document.createElement('p');
intro.textContent='הסיפור שמאחורי תחפושת הפלונטר, בתמונה המקורית ובעיצוב שאושר.';
const anchor=document.createElement('a');
anchor.className='eyal-memory-poster-image';
anchor.href=path;
anchor.target='_blank';
anchor.rel='noopener noreferrer';
anchor.setAttribute('aria-label','הגדלת עמוד הזיכרון של אייל');
const image=document.createElement('img');
image.src=path;
image.loading='lazy';
image.decoding='async';
image.alt='אייל בתחפושת פלונטר בתמונה המקורית, ולצידה הטקסט האלגנטי על סבתא שולי, התפירה והזכייה במקום השלישי';
anchor.append(image);
const link=document.createElement('a');
link.href=path;
link.target='_blank';
link.rel='noopener noreferrer';
link.className='eyal-memory-poster-link';
link.textContent='פתיחת התמונה בגודל מלא';
section.append(heading,intro,anchor,link);
const story=card.querySelector('#eyalStory');
if(story)card.insertBefore(section,story);else card.append(section);
})();